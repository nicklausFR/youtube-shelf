const start=source.indexOf('  if (message?.type === "YOUTUBE_SHELF_NATIVE_FULLSCREEN")');
const end=source.indexOf('  if (message?.type === "YOUTUBE_SHELF_SUBSCRIPTION_RESULT")',start);
