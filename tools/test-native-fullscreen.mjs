const msg={type:'YOUTUBE_SHELF_NATIVE_FULLSCREEN'};
const sender={url:'https://www.youtube.com/watch?v=test',tab:{id:42,active:true,windowId:7}};
let response;
context.handle(msg,sender,value=>response=value);
await new Promise(resolve=>setImmediate(resolve));
assert.equal(closed[0].windowId,7);assert.equal(response.ok,true);assert.equal(context.openWindows.has(7),false);
